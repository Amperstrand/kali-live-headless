#!/bin/bash
# tpm-seal.sh — seal secrets to this machine's TPM 2.0 (at rest), with
# an explicit LUKS fallback when no TPM exists.
#
# WHY THIS SHAPE: TPM 2.0 cannot execute BIP-340 (nostr schnorr)
# signatures — the spec has ECDSA/ECDH/RSA only. So a nostr nsec can
# never LIVE inside the TPM the way an RSA key can in a PKCS#11 token.
# What the TPM gives us instead: SEALING. The key blob at rest is
# encrypted by the TPM and only decryptable on THIS machine (bound to
# its PCR boot state). A stolen, powered-off machine yields nothing.
# While a service runs, the plaintext sits in RAM (unavoidable today).
#
# For the strongest owner-key story pair this with NIP-46 delegation:
# the TPM machine runs a delegated session key; the root nsec signs on
# a separate signer (phone/Amber or an offline ceremony).
#
# Usage:
#   tpm-seal.sh status                 — TPM present? which backend?
#   tpm-seal.sh seal FILE              — FILE → FILE.tpmsealed (0400)
#   tpm-seal.sh unseal FILE.tpmsealed  — plaintext to stdout
#   tpm-seal.sh seal-unit NAME FILE    — print a systemd unit snippet
#                                        that unseals at service start
#
# Backends: systemd-creds --with-key=tpm2 (needs /dev/tpmrm0) when a
# TPM exists; without one we REFUSE to pretend (a passwordless
# 'fallback' would be security theater) and say so loudly.
set -u

die() { echo "tpm-seal: $*" >&2; exit 1; }

have_tpm() { [ -c /dev/tpmrm0 ] || [ -c /dev/tpm0 ]; }
have_systemd_creds() { command -v systemd-creds >/dev/null 2>&1; }

cmd=${1:-status}

case "$cmd" in
status)
	echo "TPM device:    $(ls /dev/tpmrm0 /dev/tpm0 2>/dev/null | tr '\n' ' ')"
	have_tpm && echo "TPM:           PRESENT" || echo "TPM:           ABSENT"
	have_systemd_creds && systemd-creds has-tpm2 2>/dev/null \
		&& echo "systemd-creds: TPM2 usable" \
		|| echo "systemd-creds: $(have_systemd_creds && echo present || echo missing)"
	have_tpm || cat <<'EOF'

No TPM found. To seal owner keys (nsec, CA key) to hardware:
  * ThinkPad x280 (owner workstation): enable the TPM in BIOS —
    F1 → Security → TPM 2.0 → Enabled. (No OS change needed; the
    driver appears as /dev/tpmrm0.) Until then those keys rely on
    LUKS2 full-disk encryption at rest.
  * Fleet machines with fTPM (the Legion has one): use them for
    MACHINE-bound secrets (per-stick identity keys), not owner keys.
EOF
	;;
seal)
	F=${2:?usage: tpm-seal.sh seal FILE}
	[ -f "$F" ] || die "no such file: $F"
	have_tpm || die "no TPM on this machine — refusing to fake sealing (see: tpm-seal.sh status)"
	have_systemd_creds || die "systemd-creds not available"
	umask 077
	systemd-creds encrypt --with-key=tpm2 "$F" "$F.tpmsealed" \
		|| die "systemd-creds encrypt failed"
	chmod 0400 "$F.tpmsealed"
	echo "sealed: $F.tpmsealed ($(stat -c%s "$F.tpmsealed") bytes, TPM2-bound)"
	echo "NOW: store or destroy the plaintext — sealing only helps if '$F' goes away"
	;;
unseal)
	S=${2:?usage: tpm-seal.sh unseal FILE.tpmsealed}
	[ -f "$S" ] || die "no such file: $S"
	have_tpm || die "no TPM on this machine — this blob cannot unseal here (that is the point)"
	systemd-creds decrypt "$S" - 2>/dev/null || die "unseal failed (wrong machine? PCR state changed?)"
	;;
seal-unit)
	NAME=${2:?name}; S=${3:?sealed blob path}
	cat <<EOF
# generated by tpm-seal.sh — unseal $NAME at service start
# [Unit]
# After=tpm2.target
# [Service]
# RuntimeDirectory=$NAME
# ExecStartPre=systemd-creds decrypt $S /run/\$runtime_directory/key
# ExecStart=<your daemon, key at /run/$NAME/key>
# (RuntimeDirectory= wipes the plaintext when the unit stops)
EOF
	;;
*) die "unknown command: $cmd (status|seal|unseal|seal-unit)" ;;
esac
